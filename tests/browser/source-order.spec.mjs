import {test,expect} from '@playwright/test';
test.use({storageState:{cookies:[],origins:[]}});
test('X keeps its source sequence inside addition groups and reorders existing players without reloading them',async({page})=>{
  await page.clock.setFixedTime(new Date('2026-11-03T12:00:00Z'));
  const model={posts:Array.from({length:4},(_,i)=>({id:700+i,platform:'x',externalId:String(90000+i),url:`https://x.com/i/status/${90000+i}`,author:'creator',text:`Reference ${i}`,notes:'',topics:[],media:[],accounts:['@one'],addedAt:i===3?'2026-10-01T10:00:00Z':new Date(Date.parse('2026-11-03T10:00:00Z')+i).toISOString(),savedAt:'2026-11-03T10:00:00Z',archived:false,sourceOrder:[{account:'@one',observedAt:'2026-11-03T09:59:00Z',runOrder:1,position:i}]}))};
  await page.route('**/api/posts?scope=all',r=>r.fulfill({json:{posts:model.posts,runs:[]}}));
  await page.route('https://platform.twitter.com/widgets.js',r=>r.fulfill({contentType:'text/javascript',body:`window.twttr={widgets:{createTweet:async(id,root)=>{const f=document.createElement('iframe');f.src='https://platform.twitter.com/fixture';f.style.cssText='width:100%;height:120px';root.append(f);await new Promise(r=>f.onload=r);return f;}}};`}));
  await page.route('https://platform.twitter.com/fixture',r=>r.fulfill({contentType:'text/html',body:'<article>Original post</article>'}));
  await page.goto('/');
  const ids=()=>page.locator('.save-card').evaluateAll(cards=>cards.map(card=>card.dataset.postId));
  await expect.poll(ids).toEqual(['700','701','702','703']);
  await expect(page.locator('.save-time-separator')).toHaveText([/^\d+ new posts? added$/,/^\d+ older posts?$/]);
  await expect(page.locator('.native-embed[data-embed-state="ready"]')).toHaveCount(4);
  const root=page.frameLocator('[data-post-id="700"] .embed-stage>iframe').locator('#embed-root');
  await root.evaluate(el=>el.dataset.continuity='preserved');
  const player=await page.locator('[data-post-id="700"] .embed-stage>iframe').elementHandle();
  for(const [index,post] of model.posts.entries())post.sourceOrder[0].position=[2,0,1,-1][index];
  await expect.poll(ids,{timeout:8000}).toEqual(['701','702','700','703']);
  await expect(root).toHaveAttribute('data-continuity','preserved');
  expect(await player.evaluate(el=>el.isConnected)).toBe(true);
  await expect(page.locator('.save-time-separator')).toHaveText([/^\d+ new posts? added$/,/^\d+ older posts?$/]);
  await expect.poll(ids).toEqual(['701','702','700','703']);
  await page.clock.setFixedTime(new Date('2026-11-04T12:00:00Z'));
  await expect(page.locator('.save-time-separator')).toHaveText([/^\d+ older posts?$/],{timeout:8000});
  await expect.poll(ids).toEqual(['703','701','702','700']);
  await expect(root).toHaveAttribute('data-continuity','preserved');
  await page.clock.setFixedTime(new Date('2026-11-03T12:00:00Z'));
  await expect(page.locator('.save-time-separator')).toHaveText([/^\d+ new posts? added$/,/^\d+ older posts?$/],{timeout:8000});
  await page.locator('[data-nav-account="x:@one"]').click();
  await expect(page.locator('.save-time-separator')).toHaveCount(0);
  await expect.poll(ids).toEqual(['703','701','702','700']);
  await expect(root).toHaveAttribute('data-continuity','preserved');
  await page.getByRole('button',{name:'Grid view',exact:true}).click();await expect.poll(ids).toEqual(['703','701','702','700']);
  await expect(page.locator('.save-time-separator')).toHaveCount(0);
  await page.locator('[data-filter="all"]').click();
  await expect(page.locator('.save-time-separator')).toHaveText([/^\d+ new posts? added$/,/^\d+ older posts?$/]);
  await expect.poll(ids).toEqual(['701','702','700','703']);
});
